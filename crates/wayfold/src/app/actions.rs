pub const WORKSPACE: &str = "Workspace";
pub const BROWSER: &str = "FileBrowser";
pub const PATH_INPUT: &str = "PathInput";

pub fn bind_keys(cx: &mut App) {
    let w = Some(WORKSPACE);
    let b = Some(BROWSER);
    cx.bind_keys([
        KeyBinding::new("cmd-[", GoBack, w),
        KeyBinding::new("cmd-]", GoForward, w),
        KeyBinding::new("cmd-up", GoUp, w),
        KeyBinding::new("cmd-shift-h", GoHome, w),
        KeyBinding::new("cmd-shift-g", GoToPath, w),
        KeyBinding::new("cmd-l", FocusPath, w),
        KeyBinding::new("cmd-r", Refresh, w),
        KeyBinding::new("cmd-k", OpenCommandPalette, w),
        KeyBinding::new("cmd-t", NewTab, w),
        KeyBinding::new("cmd-w", CloseTab, w),
        KeyBinding::new("ctrl-tab", NextTab, w),
        KeyBinding::new("ctrl-shift-tab", PrevTab, w),
        KeyBinding::new("cmd-shift-d", ToggleSplit, w),
        KeyBinding::new("cmd-alt-right", FocusOtherPane, w),
        KeyBinding::new("cmd-alt-left", FocusOtherPane, w),
        KeyBinding::new("cmd-1", ViewIcons, w),
        KeyBinding::new("cmd-2", ViewList, w),
        KeyBinding::new("cmd-3", ViewColumns, w),
        KeyBinding::new("cmd-shift-.", ToggleHidden, w),
        KeyBinding::new("cmd-f", Search, w),
        KeyBinding::new("f4", ToggleTerminal, w),
        KeyBinding::new("cmd-alt-t", ToggleQueue, w),
        KeyBinding::new("cmd-shift-n", NewFolder, w),
        KeyBinding::new("cmd-alt-n", NewFile, w),
        KeyBinding::new("cmd-i", GetInfo, w),
        KeyBinding::new("cmd-shift-r", BatchRename, w),
        KeyBinding::new("cmd-alt-c", CopyPath, w),
        KeyBinding::new("cmd-ctrl-t", EditTags, w),
        KeyBinding::new("cmd-shift-k", ConnectToServer, w),
        // Browser-focused only, so inputs and the terminal keep these keys.
        KeyBinding::new("cmd-a", SelectAll, b),
        KeyBinding::new("down", SelectNext, b),
        KeyBinding::new("up", SelectPrev, b),
        KeyBinding::new("shift-down", ExtendNext, b),
        KeyBinding::new("shift-up", ExtendPrev, b),
        KeyBinding::new("left", SelectLeft, b),
        KeyBinding::new("right", SelectRight, b),
        KeyBinding::new("cmd-c", CopyItems, b),
        KeyBinding::new("cmd-x", CutItems, b),
        KeyBinding::new("cmd-v", PasteItems, b),
        KeyBinding::new("cmd-o", OpenItems, b),
        KeyBinding::new("cmd-down", OpenItems, b),
        KeyBinding::new("enter", RenameItem, b),
        KeyBinding::new("cmd-d", DuplicateItems, b),
        KeyBinding::new("cmd-backspace", TrashItems, b),
        KeyBinding::new("cmd-ctrl-a", MakeAlias, b),
        KeyBinding::new("cmd-z", Undo, b),
        KeyBinding::new("space", TogglePreview, b),
        KeyBinding::new("escape", ClosePanels, b),
        KeyBinding::new("tab", CompletePath, Some(PATH_INPUT)),
        KeyBinding::new("cmd-q", Quit, None),
    ]);
}

